HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
SOURCE = None
KANA_SOURCE = ROOT / 'config/pc/japanese-q-canonical.json'
OUT = None
STRIDE = 128
SAFE_GODAN = {
    'v5u': ('う', 'わ', 'い', 'って', 'った'),
    'v5k': ('く', 'か', 'き', 'いて', 'いた'),
    'v5k-s': ('く', 'か', 'き', 'って', 'った'),
    'v5g': ('ぐ', 'が', 'ぎ', 'いで', 'いだ'),
    'v5s': ('す', 'さ', 'し', 'して', 'した'),
    'v5t': ('つ', 'た', 'ち', 'って', 'った'),
    'v5n': ('ぬ', 'な', 'に', 'んで', 'んだ'),
    'v5b': ('ぶ', 'ば', 'び', 'んで', 'んだ'),
    'v5m': ('む', 'ま', 'み', 'んで', 'んだ'),
    'v5r': ('る', 'ら', 'り', 'って', 'った'),
}
VERB_FORMS = ('past', 'negative', 'te', 'polite', 'polite-past', 'polite-negative', 'polite-negative-past')
UNHANDLED_SPECIAL = {'adj-ix','v5r-i','v5u-s','v5aru','v5uru','v1-s','vz','vs-c'}
POLITE = {'polite': 'ます', 'polite-past': 'ました', 'polite-negative': 'ません',
          'polite-negative-past': 'ませんでした'}


def hira(value):
    return ''.join(chr(ord(c) - 0x60) if '\u30a1' <= c <= '\u30f6' else c for c in value)


def is_han(c):
    return U.name(c, '').startswith('CJK UNIFIED IDEOGRAPH') or U.name(c, '').startswith('CJK COMPATIBILITY IDEOGRAPH')


def admitted_surface(text):
    # A q word contains actual Han; kana-only entries stay in ordinary kana input.
    # Preserve attested punctuation / Latin inside the surface; only the reading
    # must be representable by the established kana code inventory.
    return bool(text) and any(is_han(c) for c in text) and not any(c in text for c in '\t\r\n')


def kana_inventory():
    # Generated by this project's independent spelling specification.
    canonical = json.loads(KANA_SOURCE.read_text(encoding='utf-8-sig'))
    if not canonical or any(not isinstance(k, str) or not isinstance(v, str)
                            or not re.fullmatch('[a-z]+', v) for k, v in canonical.items()):
        raise ValueError('Expected a kana-to-ASCII spelling JSON object')
    if any(k.startswith('ん') for k in canonical):
        raise ValueError('Contextual nasal spelling is handled by romanize')
    assert {k: canonical[k] for k in ('し', 'ち', 'つ', 'ふ', 'ぢ', 'づ', 'ゐ', 'ゑ')} == {
        'し': 'shi', 'ち': 'chi', 'つ': 'tsu', 'ふ': 'fu', 'ぢ': 'di', 'づ': 'dsu', 'ゐ': 'wi', 'ゑ': 'we'}
    return canonical


INVENTORY = {}
TOKENS = []


@lru_cache(maxsize=None)
def romanize(reading):
    reading = hira(U.normalize('NFC', reading))
    parts = []
    i = 0
    while i < len(reading):
        if reading[i] == 'ん':
            following = reading[i + 1:i + 2]
            parts.append("n'" if following and following in 'あいうえおやゆよ' else 'n')
            i += 1
            continue
        found = next((kana for kana in TOKENS if reading.startswith(kana, i)), None)
        if not found:
            return ()
        parts.append(INVENTORY[found])
        i += len(found)
    code = ''.join(parts)
    # Native ordinary nn terminal spelling is retained without expanding every
    # internal n occurrence or materialising a Cartesian product of aliases.
    return (code, code + 'n') if code.endswith('n') else (code,)


def finite_forms(surface, reading, pos):
    """Return only bounded one-step forms of an attested surface/reading pair."""
    if pos == 'v1' and surface.endswith('る') and reading.endswith('る'):
        stem, rst = surface[:-1], reading[:-1]
        endings = {'past': 'た', 'negative': 'ない', 'te': 'て', **POLITE}
    elif pos in SAFE_GODAN:
        ending, a, i, te, ta = SAFE_GODAN[pos]
        if not surface.endswith(ending) or not reading.endswith(ending):
            return []
        stem, rst = surface[:-1], reading[:-1]
        endings = {'past': ta, 'negative': a + 'ない', 'te': te,
                   **{key: i + value for key, value in POLITE.items()}}
    elif pos == 'vk' and reading.endswith('くる'):
        # The final 来/來 remains written, while its reading changes (き/こ).
        if surface.endswith(('来る', '來る')):
            stem, rst = surface[:-1], reading[:-2]
            return [(stem + end, rst + rend, key) for key, end, rend in [
                ('past', 'た', 'きた'), ('negative', 'ない', 'こない'), ('te', 'て', 'きて'),
                *[(key, value, 'き' + value) for key, value in POLITE.items()]]]
        if not surface.endswith('くる'):
            return []
        stem, rst = surface[:-2], reading[:-2]
        endings = {'past': 'きた', 'negative': 'こない', 'te': 'きて',
                   **{key: 'き' + value for key, value in POLITE.items()}}
    elif pos in ('vs-i', 'vs-s') and surface.endswith('する') and reading.endswith('する'):
        stem, rst = surface[:-2], reading[:-2]
        endings = {'past': 'した', 'te': 'して',
                   **{key: 'し' + value for key, value in POLITE.items()}}
        # vs-s has lexical negative alternations not covered by the elementary
        # Group-3 rule. Retain its dictionary/past/te/polite forms only.
        if pos == 'vs-i':
            endings['negative'] = 'しない'
    elif pos == 'adj-i' and surface.endswith('い') and reading.endswith('い'):
        stem, rst = surface[:-1], reading[:-1]
        endings = {'past': 'かった', 'negative': 'くない',
                   'negative-past': 'くなかった', 'te': 'くて'}
    else:
        return []
    return [(stem + ending, rst + ending, form) for form, ending in endings.items()]


def xml_document():
    text = gzip.decompress(SOURCE.read_bytes()).decode('utf-8')
    # Preserve DTD entity identifiers such as v1/adj-i, rather than expanded
    # descriptions. Standard XML entities remain XML entities.
    text = re.sub(r'<!DOCTYPE JMdict \[.*?\]>', '', text, count=1, flags=re.S)
    text = re.sub(r'&([A-Za-z0-9_-]+);', lambda m: m.group(0) if m[1] in ('amp', 'lt', 'gt', 'quot', 'apos') else m[1], text)
    return ET.fromstring(text)


def sparse_tsv(name, data):
    blocks = []
    path = OUT / (name + '.tsv')
    temp = path.with_suffix(path.suffix + '.tmp')
    with temp.open('wb') as file:
        for number, surface in enumerate(sorted(data, key=lambda s: s.encode('utf-8'))):
            if number % STRIDE == 0:
                blocks.append((surface, file.tell()))
            values = sorted(data[surface])
            file.write(('\t'.join([surface, *values]) + '\n').encode('utf-8'))
    temp.replace(path)
    lua = OUT / 'lua' / (name + '_index.lua')
    with lua.open('w', encoding='utf-8', newline='\n') as file:
        file.write(f'-- Generated JMdict derivative; CC BY-SA 4.0.\nreturn {{stride={STRIDE},count={len(data)},blocks={{\n')
        for surface, offset in blocks:
            file.write('{' + json.dumps(surface, ensure_ascii=False) + ',' + str(offset) + '},\n')
        file.write('}}\n')


def main():
    global INVENTORY, TOKENS, SOURCE, KANA_SOURCE, OUT
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, required=True, help='Official JMdict_e.gz source')
    parser.add_argument('--out', type=Path, required=True, help='New output directory; never overwrites a previous run')
    parser.add_argument('--kana-inventory', type=Path, default=KANA_SOURCE)
    parser.add_argument('--expected-source-sha256', help='Optional fixed source digest; mismatches abort')
    args = parser.parse_args()
    SOURCE, KANA_SOURCE, OUT = args.source, args.kana_inventory, args.out
    if OUT.exists():
        raise FileExistsError('Choose a new output directory')
    if args.expected_source_sha256 and hashlib.sha256(SOURCE.read_bytes()).hexdigest() != args.expected_source_sha256.lower():
        raise ValueError('JMdict source digest mismatch')
    OUT.mkdir(parents=True)
    (OUT / 'lua').mkdir(exist_ok=True)
    assets = ROOT / 'config/pc'
    shutil.copyfile(assets / 'jp_q_lookup.schema.yaml', OUT / 'jp_q_lookup.schema.yaml')
    INVENTORY = kana_inventory()
    TOKENS = sorted(INVENTORY, key=lambda k: (-len(k), k))
    dictionary = {}
    readings = defaultdict(set)
    codes = defaultdict(set)
    rejected = Counter()
    by_form = Counter()
    pos_counts = Counter()
    proof_count = 0
    examples = defaultdict(list)
    probe = {'食べる', '食べた', '食べない', '食べます', '面白い', '面白かった', '桜花',
             '読んだ', '書いて', '行った', '来ない', '勉強する', '勉強した'}
    document = xml_document()
    proof_path = OUT / 'jp_q_provenance.tsv'
    with proof_path.with_suffix('.tsv.tmp').open('w', encoding='utf-8', newline='\n') as proof:
        proof.write('surface\treading\tentry\tbase_surface\tbase_reading\tpos\tform\treading_restrictions\tsense\tsense_stagk\tsense_stagr\n')

        def add(surface, reading, seq, base, base_read, pos, form, restrictions, sense_no, stagk, stagr, weight):
            nonlocal proof_count
            romaji = romanize(reading)
            if not romaji:
                rejected['reading_unrepresentable'] += 1
                return
            readings[surface].add(reading)
            codes[surface].update(romaji)
            for code in romaji:
                pair = (surface, code)
                dictionary[pair] = max(dictionary.get(pair, 0), weight)
            fields = (surface, reading, seq, base, base_read, ','.join(pos), form,
                      '|'.join(restrictions), str(sense_no), '|'.join(stagk), '|'.join(stagr))
            proof.write('\t'.join(fields) + '\n')
            proof_count += 1
            by_form[form] += 1
            if surface in probe and len(examples[surface]) < 8:
                examples[surface].append(dict(zip(('surface','reading','entry','base_surface','base_reading','pos','form','reading_restrictions','sense','sense_stagk','sense_stagr'), fields)))

        for entry in document.findall('entry'):
            seq = entry.findtext('ent_seq')
            senses = []
            inherited_pos = []
            for number, sense in enumerate(entry.findall('sense'), 1):
                explicit_pos = [n.text for n in sense.findall('pos')]
                inherited_pos = explicit_pos or inherited_pos
                senses.append((number, list(inherited_pos), [n.text for n in sense.findall('stagk')],
                               [n.text for n in sense.findall('stagr')], [n.text for n in sense.findall('misc')]))
            entry_derivative_excluded = any(n.text in ('arch','obs','rare','dated') for n in entry.findall('sense/misc'))
            for form in entry.findall('k_ele'):
                surface = form.findtext('keb')
                if not admitted_surface(surface):
                    rejected['surface_without_han'] += 1
                    continue
                form_info = [n.text for n in form.findall('ke_inf')]
                for read in entry.findall('r_ele'):
                    reading = read.findtext('reb')
                    restrictions = [n.text for n in read.findall('re_restr')]
                    if read.find('re_nokanji') is not None or (restrictions and surface not in restrictions):
                        rejected['reading_restriction'] += 1
                        continue
                    reading_info = [n.text for n in read.findall('re_inf')]
                    priority = [n.text for n in form.findall('ke_pri')] + [n.text for n in read.findall('re_pri')]
                    weight = 10000 if any(x in ('ichi1','news1','spec1','gai1') for x in priority) else 3000 if priority else 1000
                    if any(x in ('oK', 'sK', 'iK') for x in form_info):
                        weight //= 10
                    applicable = [s for s in senses if (not s[2] or surface in s[2]) and (not s[3] or reading in s[3])]
                    if not applicable:
                        rejected['sense_restriction'] += 1
                        continue
                    # One dictionary record per applicable sense retains exact
                    # source applicability; generated lookups deduplicate later.
                    seen_derivations = set()
                    for number, pos, stagk, stagr, misc in applicable:
                        add(surface, reading, seq, surface, reading, pos, 'dictionary', restrictions, number, stagk, stagr, weight)
                        if (entry_derivative_excluded or UNHANDLED_SPECIAL.intersection(pos)
                                or any(x in ('oK','sK','rK','io') for x in form_info)
                                or any(x in ('ok','sk','rk','ik') for x in reading_info)):
                            rejected['noncurrent_or_irregular_derivative_senses'] += 1
                            continue
                        for part in pos:
                            for output, sound, kind in finite_forms(surface, reading, part):
                                key = output, sound, kind, part
                                if key in seen_derivations or not admitted_surface(output):
                                    continue
                                seen_derivations.add(key)
                                add(output, sound, seq, surface, reading, pos, kind, restrictions, number, stagk, stagr, max(1, weight - 1))
                                pos_counts[part] += 1

    proof_path.with_suffix('.tsv.tmp').replace(proof_path)
    header = ['# JMdict q lookup; CC BY-SA 4.0. See licenses/jp-q-sources.md.',
              '---', 'name: jp_q_lookup', 'version: "2026.10.21"', 'sort: by_weight',
              'use_preset_vocabulary: false', '...', '']
    dictionary_path = OUT / 'jp_q_lookup.dict.yaml'
    with dictionary_path.with_suffix('.yaml.tmp').open('w', encoding='utf-8', newline='\n') as file:
        file.write('\n'.join(header) + '\n')
        for (surface, code), weight in sorted(dictionary.items(), key=lambda row: (row[0][1], -row[1], row[0][0])):
            file.write(f'{surface}\t{code}\t{weight}\n')
    dictionary_path.with_suffix('.yaml.tmp').replace(dictionary_path)
    sparse_tsv('jp_q_surface_readings', readings)
    sparse_tsv('jp_q_surface_codes', codes)
    (OUT / 'kana-code-inventory.json').write_text(json.dumps(INVENTORY, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    license_source = ROOT / 'config/pc/licenses'
    (OUT / 'licenses').mkdir(exist_ok=True)
    shutil.copyfile(license_source / 'jp-q-sources.md', OUT / 'licenses/jp-q-sources.md')
    for name in ('EDRDG-licence.html', 'CC-BY-SA-4.0.txt'):
        if (license_source / name).is_file():
            shutil.copyfile(license_source / name, OUT / 'licenses' / name)
    report = {
        'source': SOURCE.name,
        'source_sha256': hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
        'kana_source': KANA_SOURCE.name,
        'kana_source_sha256': hashlib.sha256(KANA_SOURCE.read_bytes()).hexdigest(),
        'entries': len(document.findall('entry')), 'surfaces': len(readings),
        'surface_reading_pairs': sum(map(len, readings.values())),
        'dictionary_rows': len(dictionary), 'unique_codes': len({code for _, code in dictionary}),
        'provenance_rows': proof_count, 'form_source_rows': by_form,
        'generated_pos_rows': pos_counts, 'rejections': rejected,
        'max_code_length': max(len(code) for _, code in dictionary),
        'max_readings_per_surface': max(map(len, readings.values())),
        'max_codes_per_surface': max(map(len, codes.values())),
        'files_bytes': {p.name: p.stat().st_size for p in OUT.iterdir() if p.is_file()},
        'examples': examples,
    }
    (OUT / 'build-report.json').write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(json.dumps({k: v for k, v in report.items() if k != 'examples'}, ensure_ascii=True))


if __name__ == '__main__':
    main()
