"""Rebuild shared base dictionaries and English indexes from fixed public inputs."""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import re
import shutil
import tarfile

ROOT = Path(__file__).resolve().parents[2]
WORD = re.compile(r"[a-z]+(?:['-][a-z]+)*\Z", re.ASCII)


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding='utf-8', newline='\n')


def aliases(code):
    """Apply the complete pinned extension source's general spelling algebra."""
    values = {code.lower()}
    rules = [(r'1([4-7|9])', r'\1teen'), ('11', 'eleven'), ('12', 'twelve'),
             ('13', 'thirteen'), ('15', 'fifteen'), ('18', 'eighteen'),
             ('0', 'o'), ('0', 'zero'), ('1', 'one'), ('10', 'ten'),
             ('2', 'to'), ('2', 'two'), ('3', 'three'), ('4', 'for'),
             ('4', 'four'), ('5', 'five'), ('6', 'six'), ('7', 'seven'),
             ('8', 'eight'), ('9', 'nine'), (r'\+', 'plus'), (r'\.', 'dot'),
             ('@', 'at'), ('-', 'hyphen'), ('#', 'hash'), ('#', 'number'),
             ('#', 'sharp'), ('♯', 'sharp'), ('/', 'slash'), ('&', 'and'),
             ('%', 'percent'), (r'[.]', ''), (r'[+]', ''), (r'[@]', ''),
             (r'[-]', ''), (r'[_]', ''), (r'[^a-z0-9]', '')]
    for pattern, replacement in rules:
        values.update(re.sub(pattern, replacement, value) for value in list(values))
    return sorted(value for value in values if WORD.fullmatch(value)
                  and (len(value) > 1 or value == code.lower()))


def dictionary_header(name, imports=None):
    imports = '' if not imports else 'import_tables: [' + ', '.join(imports) + ']\n'
    return ('# Generated by scripts/data/rebuild_base.py.\n'
            '# Sources, transformations and notices: docs/sources/base-dictionaries.md.\n'
            '---\nname: ' + name + '\nversion: "2026.11.14.base"\n'
            'sort: by_weight\nuse_preset_vocabulary: false\n' + imports
            + 'columns: [text, code, weight]\n...\n')


def load_core(source, integrity):
    words = {}
    source_rows = 0
    for line in source.read_text(encoding='utf-8-sig').splitlines():
        word, count = line.rsplit(None, 1)
        if not WORD.fullmatch(word) or not count.isdigit() or int(count) <= 0 or word in words:
            raise ValueError('The pinned English source contains an unsupported record.')
        source_rows += 1
        if word not in integrity['english_invalid_spellings']:
            words[word] = int(count)
    return words, source_rows


def load_extensions(source, core):
    body = source.read_text(encoding='utf-8-sig').split('...\n', 1)[1]
    entries = []
    skipped = 0
    for line in body.splitlines():
        if not line or line.startswith('#'):
            continue
        fields = line.split('\t')
        text, code = fields[:2]
        keys = aliases(code)
        if re.search(r'[\u3400-\u9fff]', text) or not keys:
            skipped += 1
            continue
        weight = int(fields[2]) if len(fields) > 2 and fields[2].isdigit() else 1
        entries.append((text, code, keys, weight))
    primary = {}
    for text, code, keys, _ in entries:
        if text.lower() in core:
            primary[text] = (text.lower(), text.lower())
        elif text not in primary:
            primary[text] = (code.lower() if WORD.fullmatch(code.lower())
                             else min(keys, key=lambda key: (len(key), key)), text)
    rows, natives = {}, {}
    for text, code, keys, weight in entries:
        native_code, native_text = primary[text]
        if native_text not in core:
            natives[(native_code, native_text)] = max(weight, natives.get((native_code, native_text), 0))
        body = re.sub('[^a-z0-9]', '', text.lower()) == re.sub('[^a-z0-9]', '', code.lower())
        parent = next((primary[t] for t, c, _, _ in entries
                       if c.lower() == code.lower() and t.lower() == code.lower()), None)
        parent_code, parent_text = parent or ('', '')
        for alias in keys:
            identity = (alias, native_code, native_text)
            value = (alias, native_code, native_text, text, int(not body), weight,
                     parent_code, parent_text)
            if identity not in rows or (value[4], -weight) < (rows[identity][4], -rows[identity][5]):
                rows[identity] = value
    return [row for _, row in sorted(rows.items())], natives, len(entries), skipped


def case_forms(archive_path, core, extensions):
    collisions = {}
    for alias, code, word, shown, expansion, *_ in extensions:
        if alias == code == word and expansion == 0 and word in core and word != shown:
            collisions[word] = shown
    evidence = set()
    with tarfile.open(archive_path) as archive:
        for member in archive:
            match = re.search(r'/final/(?:english|american|british)-words\.(\d+)$', member.name)
            if member.isfile() and match and int(match[1]) <= 80:
                for word in archive.extractfile(member).read().decode('latin-1').splitlines():
                    if word in collisions:
                        evidence.add(word)
    return ''.join(f'{word}\t{int(word in evidence)}\n' for word in sorted(collisions))


def repaired_chinese(source, integrity):
    text = source.read_text(encoding='utf-8-sig')
    lines = text.splitlines()
    for repair in integrity['chinese_code_repairs']:
        if lines.count(repair['before']) != 1:
            raise ValueError('Chinese source repair no longer matches the fixed input.')
        index = lines.index(repair['before'])
        if repair['remove_duplicate']:
            if repair['after'] not in lines:
                raise ValueError('Expected canonical Chinese row is missing.')
            del lines[index]
        else:
            lines[index] = repair['after']
    text = '\n'.join(lines) + '\n'
    text = re.sub(r'(?m)^version:.*$', 'version: "2026.11.14.base"', text, count=1)
    return ('# Code integrity repairs: sources/quality/dictionary-integrity.json.\n' + text)


def build(repo):
    source_dir = repo / 'sources/base'
    manifest = json.loads((source_dir / 'source-manifest.json').read_text())
    for item in manifest['sources']:
        raw = (source_dir / item['path']).read_bytes()
        if len(raw) != item['bytes'] or hashlib.sha256(raw).hexdigest() != item['sha256']:
            raise ValueError('Public source checksum mismatch: ' + item['path'])
    integrity = json.loads((repo / 'sources/quality/dictionary-integrity.json').read_text(encoding='utf-8'))
    core, source_rows = load_core(source_dir / 'english-frequency.txt', integrity)
    extensions, natives, extension_rows, skipped = load_extensions(source_dir / 'english-extensions.dict.yaml', core)
    forms = case_forms(source_dir / 'scowl-2020.12.07.tar.gz', core, extensions)
    chinese = repaired_chinese(source_dir / 'luna_pinyin.dict.yaml', integrity)
    spec = importlib.util.spec_from_file_location('rymcp_index_builder', Path(__file__).with_name('build_english_index.py'))
    builder = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(builder)
    reports = []
    for profile in ('pc', 'official-weasel'):
        user = repo / 'config' / profile
        if not user.is_dir():
            continue
        write(user / 'luna_pinyin.dict.yaml', chinese)
        shutil.copyfile(source_dir / 'essay.txt', user / 'essay.txt')
        write(user / 'english_full.dict.yaml', dictionary_header('english_full', ['english_extensions'])
              + ''.join(f'{word}\t{word}\t{count}\n' for word, count in core.items()))
        write(user / 'english_index/vocabulary.tsv', ''.join(f'{word}\t{count}\n' for word, count in core.items()))
        write(user / 'english_extensions/entries.tsv', ''.join('\t'.join(map(str, row)) + '\n' for row in extensions))
        write(user / 'english_extensions/case_forms.tsv', forms)
        write(user / 'english_extensions.dict.yaml', dictionary_header('english_extensions')
              + ''.join(f'{text}\t{code}\t{weight}\n' for (code, text), weight in sorted(natives.items())))
        core_report = builder.build(user / 'english_index/vocabulary.tsv', user / 'english_index')
        ext_report = builder.build(user / 'english_extensions/entries.tsv', user / 'english_extensions')
        reports.append({'profile': profile, 'core_words': len(core), 'extension_rows': len(extensions),
                        'core_keys': core_report['key_count'], 'extension_keys': ext_report['key_count']})
    report = {'format': 'rymcp-base-build-v1', 'source_core_rows': source_rows,
              'core_words': len(core), 'source_extension_rows': extension_rows,
              'extension_rows_outside_english_format': skipped,
              'chinese_code_repairs': len(integrity['chinese_code_repairs']),
              'profiles': reports}
    write(repo / 'sources/base-build.json', json.dumps(report, indent=2) + '\n')
    return report


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--repo', type=Path, default=ROOT)
    print(json.dumps(build(parser.parse_args().repo.resolve()), indent=2))
